import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contract = JSON.parse(fs.readFileSync(path.join(root, "shared", "native-preview-contract.json"), "utf8"));
const cppString = (value) => `L${JSON.stringify(value)}`;
const colorRef = (value) => {
  const color = Number.parseInt(value.slice(1), 16);
  return `RGB(0x${((color >> 16) & 0xff).toString(16).padStart(2, "0").toUpperCase()}, 0x${((color >> 8) & 0xff).toString(16).padStart(2, "0").toUpperCase()}, 0x${(color & 0xff).toString(16).padStart(2, "0").toUpperCase()})`;
};
const cppIdentifier = (value) => value.replaceAll(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
const cppIds = contract.labels.map((label) => `  ${cppIdentifier(label.key)},`).join("\n");
const cppBindings = contract.labels.map((label) =>
  `    {NativeLabelId::${cppIdentifier(label.key)}, ${JSON.stringify(label.key)}, &PreviewRuntime::NativePreviewLabels::${label.cppMember}},`,
).join("\n");
const cppDefaults = contract.labels.map((label) => `    ${cppString(label.default)},`).join("\n");
const paletteKeys = ["canvas", "surface", "surfaceSubtle", "border", "text", "muted", "accent", "onAccent"];
const cppPalette = (palette) => paletteKeys.map((key) => colorRef(palette[key])).join(", ");
const metrics = contract.chrome.metrics;
const cpp = `// Generated by scripts/generate-native-preview-contract.mjs. Do not edit.
#pragma once

#include <Windows.h>

#include <array>
#include <string>

namespace mactype {

enum class NativeLabelId {
${cppIds}
};

struct GeneratedNativeLabelBinding {
  NativeLabelId id;
  const char* key;
  std::wstring PreviewRuntime::NativePreviewLabels::*member;
};

struct GeneratedNativePalette {
  COLORREF canvas;
  COLORREF surface;
  COLORREF hover;
  COLORREF border;
  COLORREF text;
  COLORREF muted;
  COLORREF accent;
  COLORREF on_accent;
};

struct GeneratedNativeChrome {
  int radius;
  int control_height;
  int toolbar_height;
  int status_height;
  int canvas_radius;
  int canvas_inset;
  bool mono_status;
};

inline constexpr std::array<GeneratedNativeLabelBinding, ${contract.labels.length}> kNativeLabelBindings{{
${cppBindings}
}};
inline constexpr std::array<const wchar_t*, ${contract.labels.length}> kNativeLabelDefaults{{
${cppDefaults}
}};
inline constexpr GeneratedNativePalette kNativeLightPalette{${cppPalette(contract.chrome.palettes.light)}};
inline constexpr GeneratedNativePalette kNativeDarkPalette{${cppPalette(contract.chrome.palettes.dark)}};
inline constexpr GeneratedNativeChrome kNativeChromeDefault{
    ${metrics.radius}, ${metrics.controlHeight}, ${metrics.toolbarHeight}, ${metrics.statusHeight},
    ${metrics.canvasRadius}, ${metrics.canvasInset}, ${metrics.monoStatus}};
inline constexpr std::array<float, ${contract.ladderSizes.length}> kNativeLadderSizes{${contract.ladderSizes.map((value) => `${value}.0F`).join(", ")}};

}
`;

const labelKeys = contract.labels.map((label) => label.key);
const defaults = Object.fromEntries(contract.labels.map((label) => [label.key, label.default]));
const ts = `// Generated by scripts/generate-native-preview-contract.mjs. Do not edit.\n` +
  `export const nativePreviewLabelKeys = ${JSON.stringify(labelKeys, null, 2)} as const;\n\n` +
  `export type NativePreviewLabelKey = (typeof nativePreviewLabelKeys)[number];\n\n` +
  `export const nativePreviewLabelDefaults: Readonly<Record<NativePreviewLabelKey, string>> = ${JSON.stringify(defaults, null, 2)};\n\n` +
  `export const nativePreviewChromeDefaults = ${JSON.stringify(contract.chrome, null, 2)} as const;\n\n` +
  `export const nativePreviewLadderSizes = ${JSON.stringify(contract.ladderSizes)} as const;\n`;

const outputs = [
  [path.join(root, "preview-helper", "include", "generated_native_preview.h"), cpp],
  [path.join(root, "control-center", "src", "generated", "nativePreview.ts"), ts],
];
for (const [output, content] of outputs) {
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, content.replaceAll("\r\n", "\n"), "utf8");
}
